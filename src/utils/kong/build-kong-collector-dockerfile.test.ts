import { describe, it, expect } from '@rstest/core';
import { buildKongCollectorDockerfile } from './build-kong-collector-dockerfile';

describe('buildKongCollectorDockerfile', () => {
  describe('Standard use cases', () => {
    it('should bake the config into the pinned contrib image', () => {
      const dockerfile = buildKongCollectorDockerfile();
      expect(dockerfile).toContain(
        'FROM otel/opentelemetry-collector-contrib:0.164.0',
      );
      expect(dockerfile).toContain(
        'COPY config.yaml /etc/otelcol-contrib/config.yaml',
      );
    });
  });

  describe('Edge cases', () => {
    it('should say how it was generated', () => {
      expect(buildKongCollectorDockerfile()).toContain(
        '# Generated by: npx tsdevstack infra:build-kong',
      );
    });
  });
});
