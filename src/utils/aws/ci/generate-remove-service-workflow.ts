/**
 * Generate Remove Service Workflow
 *
 * Creates the GitHub Actions workflow for removing a service from cloud.
 * Uses text inputs (not checkboxes) since removal is:
 * 1. Infrequent (extra friction is good)
 * 2. Destructive (confirmation required)
 * 3. For services that may no longer be in config.json
 */

/* eslint-disable no-useless-escape */

import type { CIConfig } from './types';

/**
 * Generate the remove-service workflow YAML content
 *
 * @param config - CI configuration with environments
 * @param mode - 'user' for end-user projects (npx tsdevstack), 'framework' for monorepo development
 */
export function generateRemoveServiceWorkflow(
  config: CIConfig,
  mode: 'user' | 'framework' = 'user',
): string {
  // Keep lowercase env names (matches terraform dirs, credentials file)
  const envOptions = config.environments
    .map((env) => `          - ${env}`)
    .join('\n');

  const cli =
    mode === 'framework'
      ? 'node packages/cli-core/dist/cli.js'
      : 'npx tsdevstack';

  const headerComment =
    mode === 'framework'
      ? `# Framework development workflow - Remove Service
# Internal: uses monorepo build + npm link`
      : `# Remove Service workflow - manual trigger
# Generated by tsdevstack infra:generate-ci
# Do not edit manually - regenerate with infra:generate-ci
#
# This workflow removes a service from cloud (one environment at a time).
# After removing from all environments, run locally:
#   npx tsdevstack remove-service <service-name>`;

  const workflowName =
    mode === 'framework' ? 'Framework: Remove Service' : 'Remove Service';

  const buildSteps =
    mode === 'framework'
      ? `
      # Only build CLI packages - no need to build apps for service removal
      - name: Build CLI
        run: npm run build:libs

      # TEMP: Link CLI globally for internal subprocess calls
      - name: Link CLI globally
        run: cd packages/cli-core && npm link
`
      : '';

  return `${headerComment}

name: "${workflowName}"

on:
  workflow_dispatch:
    inputs:
      environment:
        description: 'Target environment'
        required: true
        type: choice
        options:
${envOptions}
      service_name:
        description: 'Service name to remove (e.g., order-service)'
        required: true
        type: string
      confirm:
        description: 'Type service name again to confirm'
        required: true
        type: string
      dry_run:
        description: 'Dry run (show what would be deleted without deleting)'
        required: false
        type: boolean
        default: false

jobs:
  remove:
    runs-on: ubuntu-latest
    permissions:
      contents: read
      id-token: write

    steps:
      - uses: actions/checkout@v4

      # Validate confirmation matches service name
      - name: Validate confirmation
        run: |
          if [ "\${{ inputs.service_name }}" != "\${{ inputs.confirm }}" ]; then
            echo "❌ Confirmation doesn't match service name"
            echo ""
            echo "You entered:"
            echo "  Service name: \${{ inputs.service_name }}"
            echo "  Confirm:      \${{ inputs.confirm }}"
            echo ""
            echo "These must match exactly to proceed."
            exit 1
          fi
          echo "✅ Confirmation matches"

      # Set secret names for dynamic lookup (GitHub requires $GITHUB_ENV for secrets[env.X] pattern)
      - name: Set environment variables
        run: |
          ENV_UPPER=\$(echo '\${{ inputs.environment }}' | tr '[:lower:]' '[:upper:]')
          echo "AWS_ROLE_ARN_NAME=AWS_ROLE_ARN_\${ENV_UPPER}" >> \$GITHUB_ENV
          echo "AWS_REGION_NAME=AWS_REGION_\${ENV_UPPER}" >> \$GITHUB_ENV

      - uses: actions/setup-node@v4
        with:
          node-version: '20'
          cache: 'npm'

      - name: Install dependencies
        run: npm ci
${buildSteps}
      # Authenticate to AWS via OIDC
      - uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets[env.AWS_ROLE_ARN_NAME] }}
          aws-region: \${{ secrets[env.AWS_REGION_NAME] }}

      - name: Setup Terraform
        uses: hashicorp/setup-terraform@v3
        with:
          terraform_version: 1.9.0

      - name: Remove service from cloud
        run: |
          FLAGS="--env \${{ inputs.environment }} --confirm"
          if [ "\${{ inputs.dry_run }}" = "true" ]; then
            FLAGS="\$FLAGS --dry-run"
          fi
          ${cli} infra:remove-service \${{ inputs.service_name }} \$FLAGS

      - name: Summary
        if: success()
        run: |
          if [ "\${{ inputs.dry_run }}" = "true" ]; then
            echo "## Dry Run Complete" >> \$GITHUB_STEP_SUMMARY
            echo "" >> \$GITHUB_STEP_SUMMARY
            echo "No resources were deleted. Review the output above to see what would be removed." >> \$GITHUB_STEP_SUMMARY
          else
            echo "## Service Removed" >> \$GITHUB_STEP_SUMMARY
            echo "" >> \$GITHUB_STEP_SUMMARY
            echo "**\${{ inputs.service_name }}** has been removed from **\${{ inputs.environment }}**." >> \$GITHUB_STEP_SUMMARY
            echo "" >> \$GITHUB_STEP_SUMMARY
            echo "### Next Steps" >> \$GITHUB_STEP_SUMMARY
            echo "" >> \$GITHUB_STEP_SUMMARY
            echo "1. If this service is deployed in other environments, run this workflow for each one" >> \$GITHUB_STEP_SUMMARY
            echo "2. After removing from all environments, run locally:" >> \$GITHUB_STEP_SUMMARY
            echo "   \\\`\\\`\\\`" >> \$GITHUB_STEP_SUMMARY
            echo "   npx tsdevstack remove-service \${{ inputs.service_name }}" >> \$GITHUB_STEP_SUMMARY
            echo "   \\\`\\\`\\\`" >> \$GITHUB_STEP_SUMMARY
            echo "3. Commit the config.json changes" >> \$GITHUB_STEP_SUMMARY
            echo "4. Redeploy Kong to update routes:" >> \$GITHUB_STEP_SUMMARY
            echo "   \\\`\\\`\\\`" >> \$GITHUB_STEP_SUMMARY
            echo "   npx tsdevstack infra:kong-deploy --env \${{ inputs.environment }}" >> \$GITHUB_STEP_SUMMARY
            echo "   \\\`\\\`\\\`" >> \$GITHUB_STEP_SUMMARY
          fi
`;
}
