import { describe, it, expect } from '@rstest/core';
import { generatePrWorkflow } from './generate-pr-workflow';

describe('generatePrWorkflow', () => {
  it('should return a string', () => {
    const result = generatePrWorkflow();
    expect(typeof result).toBe('string');
  });

  it('should be named Quality Check', () => {
    const result = generatePrWorkflow();
    expect(result).toContain('name: Quality Check');
  });

  it('should trigger on pull_request to main', () => {
    const result = generatePrWorkflow();
    expect(result).toContain('on:');
    expect(result).toContain('pull_request:');
    expect(result).toContain('branches: [main]');
  });

  it('should use ubuntu-latest runner', () => {
    const result = generatePrWorkflow();
    expect(result).toContain('runs-on: ubuntu-latest');
  });

  it('should checkout code', () => {
    const result = generatePrWorkflow();
    expect(result).toContain('actions/checkout@v4');
  });

  it('should setup Node.js 20', () => {
    const result = generatePrWorkflow();
    expect(result).toContain('actions/setup-node@v4');
    expect(result).toContain("node-version: '20'");
  });

  it('should cache npm dependencies', () => {
    const result = generatePrWorkflow();
    expect(result).toContain("cache: 'npm'");
  });

  it('should install dependencies', () => {
    const result = generatePrWorkflow();
    expect(result).toContain('npm ci');
  });

  it('should run build step', () => {
    const result = generatePrWorkflow();
    expect(result).toContain('name: Build');
    expect(result).toContain('npm run build');
  });

  it('should run lint step', () => {
    const result = generatePrWorkflow();
    expect(result).toContain('name: Lint');
    expect(result).toContain('npm run lint');
  });

  it('should run type check step', () => {
    const result = generatePrWorkflow();
    expect(result).toContain('name: Type check');
    expect(result).toContain('npm run tsc');
  });

  it('should run test step', () => {
    const result = generatePrWorkflow();
    expect(result).toContain('name: Test');
    expect(result).toContain('npm run test');
  });

  it('should run security audit step', () => {
    const result = generatePrWorkflow();
    expect(result).toContain('name: Security audit');
    expect(result).toContain('npm audit --audit-level=high');
  });

  it('should not fail PR on security audit (continue-on-error)', () => {
    const result = generatePrWorkflow();
    expect(result).toContain('continue-on-error: true');
  });

  it('should include generator comment', () => {
    const result = generatePrWorkflow();
    expect(result).toContain('Generated by tsdevstack infra:init-ci');
    expect(result).toContain('Do not edit manually');
  });
});
