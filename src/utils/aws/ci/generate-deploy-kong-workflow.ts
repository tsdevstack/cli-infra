/**
 * Generate Deploy Kong Workflow
 *
 * Creates the GitHub Actions workflow for deploying Kong Gateway.
 */

/* eslint-disable no-useless-escape */

import type { CIConfig } from './types';

/**
 * Generate the deploy-kong workflow YAML content
 *
 * @param config - CI configuration with environments
 */
export function generateDeployKongWorkflow(config: CIConfig): string {
  // Keep lowercase env names (matches terraform dirs, credentials file)
  const envOptions = config.environments
    .map((env) => `          - ${env}`)
    .join('\n');

  return `# Deploy Kong Gateway workflow - manual trigger
# Generated by tsdevstack infra:generate-ci
# Do not edit manually - regenerate with infra:generate-ci

name: Deploy Kong Gateway

on:
  workflow_dispatch:
    inputs:
      environment:
        description: 'Target environment'
        required: true
        type: choice
        options:
${envOptions}
      tag:
        description: 'Image tag (defaults to commit SHA)'
        required: false
        type: string

jobs:
  deploy:
    runs-on: ubuntu-latest
    permissions:
      contents: read
      id-token: write

    steps:
      - uses: actions/checkout@v4

      # Set secret names for dynamic lookup (GitHub requires $GITHUB_ENV for secrets[env.X] pattern)
      - name: Set environment variables
        run: |
          ENV_UPPER=\$(echo '\${{ inputs.environment }}' | tr '[:lower:]' '[:upper:]')
          echo "AWS_ROLE_ARN_NAME=AWS_ROLE_ARN_\${ENV_UPPER}" >> \$GITHUB_ENV
          echo "AWS_REGION_NAME=AWS_REGION_\${ENV_UPPER}" >> \$GITHUB_ENV
          echo "IMAGE_TAG=\${{ inputs.tag || github.sha }}" >> \$GITHUB_ENV

      - uses: actions/setup-node@v4
        with:
          node-version: '20'
          cache: 'npm'

      - name: Install dependencies
        run: npm ci

      - name: Build
        run: npm run build

      # TEMP: Link CLI globally for internal subprocess calls (remove when published to npm)
      - name: Link CLI globally
        run: cd packages/cli-core && npm link

      # Authenticate to AWS via OIDC
      - uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets[env.AWS_ROLE_ARN_NAME] }}
          aws-region: \${{ secrets[env.AWS_REGION_NAME] }}

      # Enable containerd for BuildKit cache export support
      - name: Enable containerd image store
        run: |
          echo '{"features":{"containerd-snapshotter":true}}' | sudo tee /etc/docker/daemon.json
          sudo systemctl restart docker

      - name: Login to Amazon ECR
        uses: aws-actions/amazon-ecr-login@v2

      - name: Build Kong
        run: node packages/cli-core/dist/cli.js infra:build-kong --env \${{ inputs.environment }} --tag \${{ env.IMAGE_TAG }}

      - name: Deploy Kong
        run: node packages/cli-core/dist/cli.js infra:deploy-kong --env \${{ inputs.environment }} --tag \${{ env.IMAGE_TAG }}
`;
}
