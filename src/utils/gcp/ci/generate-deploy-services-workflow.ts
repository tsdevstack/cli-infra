/**
 * Generate Deploy Services Workflow
 *
 * Creates the GitHub Actions workflow for deploying services with
 * boolean checkboxes for each service.
 */

/* eslint-disable no-useless-escape */

import type { CIConfig } from './types';
import { toTerraformId } from '../../terraform';

/**
 * Service configuration (subset of FrameworkService)
 */
interface ServiceConfig {
  name: string;
  type: string;
}

/**
 * Generate the deploy-services workflow YAML content
 *
 * @param config - CI configuration with environments
 * @param services - List of deployable services from framework config
 */
export function generateDeployServicesWorkflow(
  config: CIConfig,
  services: ServiceConfig[],
): string {
  // Filter to deployable services (nestjs, nextjs, spa)
  const deployableServices = services.filter(
    (s) => s.type === 'nestjs' || s.type === 'nextjs' || s.type === 'spa',
  );

  // Keep lowercase env names (matches terraform dirs, credentials file)
  const envOptions = config.environments
    .map((env) => `          - ${env}`)
    .join('\n');

  // Generate service boolean inputs
  const serviceInputs = deployableServices
    .map(
      (s) => `      ${toTerraformId(s.name)}:
        description: 'Deploy ${s.name}'
        type: boolean
        default: true`,
    )
    .join('\n');

  // Generate if conditions for service list builder
  const serviceConditions = deployableServices
    .map(
      (s) =>
        `          if [ "\${{ inputs.${toTerraformId(s.name)} }}" == "true" ]; then SERVICES="$SERVICES ${s.name}"; fi`,
    )
    .join('\n');

  return `# Deploy Services workflow - manual trigger
# Generated by tsdevstack infra:generate-ci
# Do not edit manually - regenerate with infra:generate-ci

name: "Deploy Services"

on:
  workflow_dispatch:
    inputs:
      environment:
        description: 'Target environment'
        required: true
        type: choice
        options:
${envOptions}
      tag:
        description: 'Image tag (defaults to commit SHA)'
        required: false
        type: string

      # --- Generated by infra:generate-ci ---
${serviceInputs}
      # --- End generated ---

jobs:
  deploy:
    runs-on: ubuntu-latest
    permissions:
      contents: read
      id-token: write

    steps:
      - uses: actions/checkout@v4

      # Set secret names for dynamic lookup (GitHub requires $GITHUB_ENV for secrets[env.X] pattern)
      - name: Set environment variables
        run: |
          ENV_UPPER=\$(echo '\${{ inputs.environment }}' | tr '[:lower:]' '[:upper:]')
          echo "GCP_WIF_NAME=GCP_WIF_\${ENV_UPPER}" >> \$GITHUB_ENV
          echo "GCP_SA_NAME=GCP_SA_\${ENV_UPPER}" >> \$GITHUB_ENV
          echo "GCP_REGION_NAME=GCP_REGION_\${ENV_UPPER}" >> \$GITHUB_ENV
          echo "IMAGE_TAG=\${{ inputs.tag || github.sha }}" >> \$GITHUB_ENV

      - uses: actions/setup-node@v4
        with:
          node-version: '20'
          cache: 'npm'

      - name: Install dependencies
        run: npm ci

      - name: Build
        run: npm run build

      # Authenticate to GCP via WIF
      - uses: google-github-actions/auth@v2
        with:
          workload_identity_provider: \${{ secrets[env.GCP_WIF_NAME] }}
          service_account: \${{ secrets[env.GCP_SA_NAME] }}

      - uses: google-github-actions/setup-gcloud@v2

      - name: Setup Terraform
        uses: hashicorp/setup-terraform@v3
        with:
          terraform_version: 1.9.0

      # Initialize Terraform to read outputs (artifact registry URL)
      - name: Initialize Terraform
        run: |
          cd infrastructure/terraform/\${{ inputs.environment }}
          terraform init -backend-config="credentials=\$GOOGLE_APPLICATION_CREDENTIALS"

      # Enable containerd for BuildKit cache export support
      - name: Enable containerd image store
        run: |
          echo '{"features":{"containerd-snapshotter":true}}' | sudo tee /etc/docker/daemon.json
          sudo systemctl restart docker

      - name: Configure Docker for Artifact Registry
        run: gcloud auth configure-docker \${{ secrets[env.GCP_REGION_NAME] }}-docker.pkg.dev

      # Free up disk space for Docker builds
      - name: Free disk space
        run: |
          echo "Disk space before cleanup:"
          df -h /
          sudo rm -rf /usr/share/dotnet /usr/local/lib/android /opt/ghc /opt/hostedtoolcache/CodeQL
          sudo rm -rf /usr/share/swift /usr/local/share/boost /usr/share/miniconda
          docker system prune -af
          echo "Disk space after cleanup:"
          df -h /

      - name: Deploy selected services
        run: |
          # --- Generated by infra:generate-ci ---
          SERVICES=""
${serviceConditions}
          # --- End generated ---

          if [ -z "$SERVICES" ]; then
            echo "No services selected"
            exit 0
          fi

          SERVICES_CSV=$(echo $SERVICES | tr ' ' ',')
          echo "Deploying: $SERVICES_CSV"

          npx tsdevstack infra:deploy-services --env \${{ inputs.environment }} --service "$SERVICES_CSV" --tag \${{ env.IMAGE_TAG }}
        env:
          GCP_REGION: \${{ secrets[env.GCP_REGION_NAME] }}
`;
}
