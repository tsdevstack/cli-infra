import { describe, it, expect } from '@rstest/core';
import { generateRemoveServiceWorkflow } from './generate-remove-service-workflow';
import type { CIConfig } from './types';

describe('generateRemoveServiceWorkflow', () => {
  const createConfig = (environments: string[]): CIConfig => ({
    provider: 'github',
    environments,
  });

  it('should return a string', () => {
    const result = generateRemoveServiceWorkflow(createConfig(['dev']));
    expect(typeof result).toBe('string');
  });

  it('should be named Remove Service', () => {
    const result = generateRemoveServiceWorkflow(createConfig(['dev']));
    expect(result).toContain('name: "Remove Service');
  });

  it('should use workflow_dispatch trigger', () => {
    const result = generateRemoveServiceWorkflow(createConfig(['dev']));
    expect(result).toContain('workflow_dispatch:');
  });

  it('should include environment choice', () => {
    const result = generateRemoveServiceWorkflow(createConfig(['dev', 'prod']));
    expect(result).toContain('type: choice');
    expect(result).toContain('- dev');
    expect(result).toContain('- prod');
  });

  it('should include service_name text input', () => {
    const result = generateRemoveServiceWorkflow(createConfig(['dev']));
    expect(result).toContain('service_name:');
    expect(result).toContain('type: string');
    expect(result).toContain('required: true');
  });

  it('should include confirm text input', () => {
    const result = generateRemoveServiceWorkflow(createConfig(['dev']));
    expect(result).toContain('confirm:');
    expect(result).toContain('Type service name again to confirm');
  });

  it('should include dry_run boolean input', () => {
    const result = generateRemoveServiceWorkflow(createConfig(['dev']));
    expect(result).toContain('dry_run:');
    expect(result).toContain('type: boolean');
    expect(result).toContain('default: false');
  });

  it('should include confirmation validation step', () => {
    const result = generateRemoveServiceWorkflow(createConfig(['dev']));
    expect(result).toContain('Validate confirmation');
    expect(result).toContain('service_name');
    expect(result).toContain('confirm');
  });

  it('should require WIF permissions', () => {
    const result = generateRemoveServiceWorkflow(createConfig(['dev']));
    expect(result).toContain('id-token: write');
  });

  it('should authenticate via WIF', () => {
    const result = generateRemoveServiceWorkflow(createConfig(['dev']));
    expect(result).toContain('google-github-actions/auth@v2');
  });

  it('should setup Terraform for state sync', () => {
    const result = generateRemoveServiceWorkflow(createConfig(['dev']));
    expect(result).toContain('hashicorp/setup-terraform@v3');
    expect(result).toContain('terraform_version');
  });

  it('should generate Terraform files before remove', () => {
    const result = generateRemoveServiceWorkflow(createConfig(['dev']));
    expect(result).toContain('infra:generate');
  });

  it('should run infra:remove-service command', () => {
    const result = generateRemoveServiceWorkflow(createConfig(['dev']));
    expect(result).toContain('infra:remove-service');
    expect(result).toContain('--confirm');
  });

  it('should support dry-run flag', () => {
    const result = generateRemoveServiceWorkflow(createConfig(['dev']));
    expect(result).toContain('--dry-run');
  });

  it('should include summary step', () => {
    const result = generateRemoveServiceWorkflow(createConfig(['dev']));
    expect(result).toContain('GITHUB_STEP_SUMMARY');
  });

  it('should include generator comment', () => {
    const result = generateRemoveServiceWorkflow(createConfig(['dev']));
    expect(result).toContain('Generated by tsdevstack infra:generate-ci');
  });

  it('should include next steps in summary', () => {
    const result = generateRemoveServiceWorkflow(createConfig(['dev']));
    expect(result).toContain('npx tsdevstack remove-service');
    expect(result).toContain('infra:kong-deploy');
  });

  describe('user mode (default)', () => {
    it('should use npx tsdevstack', () => {
      const result = generateRemoveServiceWorkflow(createConfig(['dev']));
      expect(result).toContain('npx tsdevstack');
      expect(result).not.toContain('node packages/cli-core/dist/cli.js');
      expect(result).not.toContain('npm link');
    });

    it('should not include build steps', () => {
      const result = generateRemoveServiceWorkflow(createConfig(['dev']));
      expect(result).not.toContain('build:libs');
    });
  });
});
