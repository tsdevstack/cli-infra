/**
 * Generate Deploy Load Balancer Workflow
 *
 * Creates the GitHub Actions workflow for deploying the Load Balancer.
 */

/* eslint-disable no-useless-escape */

import type { CIConfig } from './types';

/**
 * Generate the deploy-lb workflow YAML content
 *
 * @param config - CI configuration with environments
 * @param mode - 'user' for end-user projects (npx tsdevstack), 'framework' for monorepo development
 */
export function generateDeployLbWorkflow(
  config: CIConfig,
  mode: 'user' | 'framework' = 'user',
): string {
  // Keep lowercase env names (matches terraform dirs, credentials file)
  const envOptions = config.environments
    .map((env) => `          - ${env}`)
    .join('\n');

  const cli =
    mode === 'framework'
      ? 'node packages/cli-core/dist/cli.js'
      : 'npx tsdevstack';

  const headerComment =
    mode === 'framework'
      ? `# Framework development workflow - Deploy Load Balancer
# Internal: uses monorepo build + npm link`
      : `# Deploy Load Balancer workflow - manual trigger
# Generated by tsdevstack infra:generate-ci
# Do not edit manually - regenerate with infra:generate-ci`;

  const workflowName =
    mode === 'framework'
      ? 'Framework: Deploy Load Balancer'
      : 'Deploy Load Balancer';

  const buildSteps =
    mode === 'framework'
      ? `
      # Only build CLI packages - no need to build apps for LB deployment
      - name: Build CLI
        run: npm run build:libs

      # TEMP: Link CLI globally for internal subprocess calls
      - name: Link CLI globally
        run: cd packages/cli-core && npm link
`
      : '';

  return `${headerComment}

name: "${workflowName}"

on:
  workflow_dispatch:
    inputs:
      environment:
        description: 'Target environment'
        required: true
        type: choice
        options:
${envOptions}

jobs:
  deploy:
    runs-on: ubuntu-latest
    permissions:
      contents: read
      id-token: write

    steps:
      - uses: actions/checkout@v4

      # Set secret names for dynamic lookup (GitHub requires $GITHUB_ENV for secrets[env.X] pattern)
      - name: Set environment variables
        run: |
          ENV_UPPER=\$(echo '\${{ inputs.environment }}' | tr '[:lower:]' '[:upper:]')
          echo "GCP_WIF_NAME=GCP_WIF_\${ENV_UPPER}" >> \$GITHUB_ENV
          echo "GCP_SA_NAME=GCP_SA_\${ENV_UPPER}" >> \$GITHUB_ENV
          echo "GCP_REGION_NAME=GCP_REGION_\${ENV_UPPER}" >> \$GITHUB_ENV

      - uses: actions/setup-node@v4
        with:
          node-version: '20'
          cache: 'npm'

      - name: Install dependencies
        run: npm ci
${buildSteps}
      # Authenticate to GCP via WIF
      - uses: google-github-actions/auth@v2
        with:
          workload_identity_provider: \${{ secrets[env.GCP_WIF_NAME] }}
          service_account: \${{ secrets[env.GCP_SA_NAME] }}

      - uses: google-github-actions/setup-gcloud@v2

      - name: Setup Terraform
        uses: hashicorp/setup-terraform@v3
        with:
          terraform_version: 1.9.0

      - name: Deploy Load Balancer
        run: ${cli} infra:deploy-lb --env \${{ inputs.environment }} --auto-approve
        env:
          GCP_REGION: \${{ secrets[env.GCP_REGION_NAME] }}
`;
}
