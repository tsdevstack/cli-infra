import { describe, it, expect } from '@rstest/core';
import { generateDeployWorkflow } from './generate-deploy-workflow';
import type { CIConfig } from './types';

describe('generateDeployWorkflow', () => {
  const createConfig = (environments: string[]): CIConfig => ({
    provider: 'github',
    environments,
  });

  it('should return a string', () => {
    const result = generateDeployWorkflow(createConfig(['dev']));
    expect(typeof result).toBe('string');
  });

  it('should be named Deploy', () => {
    const result = generateDeployWorkflow(createConfig(['dev']));
    expect(result).toContain('name: "Deploy');
  });

  it('should use workflow_dispatch trigger', () => {
    const result = generateDeployWorkflow(createConfig(['dev']));
    expect(result).toContain('workflow_dispatch:');
  });

  it('should include environment choice with all environments', () => {
    const result = generateDeployWorkflow(
      createConfig(['dev', 'staging', 'prod']),
    );
    expect(result).toContain('type: choice');
    expect(result).toContain('- dev');
    expect(result).toContain('- staging');
    expect(result).toContain('- prod');
  });

  it('should include optional tag input', () => {
    const result = generateDeployWorkflow(createConfig(['dev']));
    expect(result).toContain('tag:');
    expect(result).toContain('required: false');
  });

  it('should require id-token write permission for WIF', () => {
    const result = generateDeployWorkflow(createConfig(['dev']));
    expect(result).toContain('id-token: write');
  });

  it('should authenticate to GCP via WIF', () => {
    const result = generateDeployWorkflow(createConfig(['dev']));
    expect(result).toContain('google-github-actions/auth@v2');
    expect(result).toContain('workload_identity_provider');
    expect(result).toContain('service_account');
  });

  it('should setup gcloud', () => {
    const result = generateDeployWorkflow(createConfig(['dev']));
    expect(result).toContain('google-github-actions/setup-gcloud@v2');
  });

  it('should setup Terraform', () => {
    const result = generateDeployWorkflow(createConfig(['dev']));
    expect(result).toContain('hashicorp/setup-terraform@v3');
  });

  it('should configure Docker for Artifact Registry', () => {
    const result = generateDeployWorkflow(createConfig(['dev']));
    expect(result).toContain('gcloud auth configure-docker');
  });

  it('should run Bootstrap step', () => {
    const result = generateDeployWorkflow(createConfig(['dev']));
    expect(result).toContain('name: Bootstrap');
    expect(result).toContain('infra:bootstrap');
  });

  it('should wait for IAM propagation after Bootstrap', () => {
    const result = generateDeployWorkflow(createConfig(['dev']));
    expect(result).toContain('name: Wait for IAM propagation');
    expect(result).toContain('sleep 20');
  });

  it('should push framework secrets', () => {
    const result = generateDeployWorkflow(createConfig(['dev']));
    expect(result).toContain('name: Push Framework Secrets');
    expect(result).toContain('cloud-secrets:push');
    expect(result).toContain('--skip-user-secrets');
  });

  it('should run Deploy step', () => {
    const result = generateDeployWorkflow(createConfig(['dev']));
    expect(result).toContain('name: "Deploy');
    expect(result).toContain('infra:deploy');
    expect(result).toContain('--auto-approve');
  });

  it('should include generator comment', () => {
    const result = generateDeployWorkflow(createConfig(['dev']));
    expect(result).toContain('Generated by tsdevstack infra:init-ci');
  });

  it('should not include scheduler deployment (separate workflow)', () => {
    const result = generateDeployWorkflow(createConfig(['dev']));
    expect(result).not.toContain('infra:deploy-schedulers');
    expect(result).toContain('Scheduled jobs are deployed separately');
  });

  it('should not have separate worker deployment step (workers deploy via infra:deploy)', () => {
    const result = generateDeployWorkflow(createConfig(['dev']));
    // Workers are deployed automatically as part of infra:deploy-services (coupled deployment)
    // No separate infra:worker-deploy command exists
    expect(result).not.toContain('infra:worker-deploy');
  });

  it('should run security audit step', () => {
    const result = generateDeployWorkflow(createConfig(['dev']));
    expect(result).toContain('name: Security audit');
    expect(result).toContain('npm audit --audit-level=high');
  });

  it('should warn but not block deploy on audit vulnerabilities (continue-on-error)', () => {
    const result = generateDeployWorkflow(createConfig(['dev']));
    expect(result).toContain('continue-on-error: true');
  });

  describe('user mode (default)', () => {
    it('should use npx tsdevstack', () => {
      const result = generateDeployWorkflow(createConfig(['dev']));
      expect(result).toContain('npx tsdevstack');
      expect(result).not.toContain('node packages/cli-core/dist/cli.js');
      expect(result).not.toContain('npm link');
    });

    it('should include npm run build', () => {
      const result = generateDeployWorkflow(createConfig(['dev']));
      expect(result).toContain('npm run build');
    });
  });
});
