import { describe, it, expect } from '@rstest/core';
import { generateDeployKongWorkflow } from './generate-deploy-kong-workflow';
import type { CIConfig } from './types';

describe('generateDeployKongWorkflow', () => {
  const createConfig = (environments: string[]): CIConfig => ({
    provider: 'github',
    environments,
  });

  it('should return a string', () => {
    const result = generateDeployKongWorkflow(createConfig(['dev']));
    expect(typeof result).toBe('string');
  });

  it('should be named Deploy Kong Gateway', () => {
    const result = generateDeployKongWorkflow(createConfig(['dev']));
    expect(result).toContain('name: "Deploy Kong Gateway');
  });

  it('should use workflow_dispatch trigger', () => {
    const result = generateDeployKongWorkflow(createConfig(['dev']));
    expect(result).toContain('workflow_dispatch:');
  });

  it('should include environment choice', () => {
    const result = generateDeployKongWorkflow(createConfig(['dev', 'prod']));
    expect(result).toContain('type: choice');
    expect(result).toContain('- dev');
    expect(result).toContain('- prod');
  });

  it('should include optional tag input', () => {
    const result = generateDeployKongWorkflow(createConfig(['dev']));
    expect(result).toContain('tag:');
    expect(result).toContain('required: false');
  });

  it('should require WIF permissions', () => {
    const result = generateDeployKongWorkflow(createConfig(['dev']));
    expect(result).toContain('id-token: write');
  });

  it('should authenticate via WIF', () => {
    const result = generateDeployKongWorkflow(createConfig(['dev']));
    expect(result).toContain('google-github-actions/auth@v2');
  });

  it('should enable containerd for BuildKit', () => {
    const result = generateDeployKongWorkflow(createConfig(['dev']));
    expect(result).toContain('containerd-snapshotter');
    expect(result).toContain('docker');
  });

  it('should configure Docker for Artifact Registry', () => {
    const result = generateDeployKongWorkflow(createConfig(['dev']));
    expect(result).toContain('gcloud auth configure-docker');
  });

  it('should run Build Kong step', () => {
    const result = generateDeployKongWorkflow(createConfig(['dev']));
    expect(result).toContain('name: Build Kong');
    expect(result).toContain('infra:build-kong');
  });

  it('should run Deploy Kong step', () => {
    const result = generateDeployKongWorkflow(createConfig(['dev']));
    expect(result).toContain('name: "Deploy Kong');
    expect(result).toContain('infra:deploy-kong');
  });

  it('should setup Terraform for reading outputs', () => {
    const result = generateDeployKongWorkflow(createConfig(['dev']));
    expect(result).toContain('hashicorp/setup-terraform@v3');
    expect(result).toContain('terraform_version');
  });

  it('should generate Terraform files before init', () => {
    const result = generateDeployKongWorkflow(createConfig(['dev']));
    expect(result).toContain('infra:generate');
    expect(result).toContain('terraform init');
  });

  it('should include generator comment', () => {
    const result = generateDeployKongWorkflow(createConfig(['dev']));
    expect(result).toContain('Generated by tsdevstack infra:generate-ci');
  });

  describe('user mode (default)', () => {
    it('should use npx tsdevstack', () => {
      const result = generateDeployKongWorkflow(createConfig(['dev']));
      expect(result).toContain('npx tsdevstack');
      expect(result).not.toContain('node packages/cli-core/dist/cli.js');
      expect(result).not.toContain('npm link');
    });

    it('should include npm run build', () => {
      const result = generateDeployKongWorkflow(createConfig(['dev']));
      expect(result).toContain('npm run build');
    });
  });
});
