import { describe, it, expect } from '@rstest/core';
import { generateRemoveDetachedWorkerWorkflow } from './generate-remove-detached-worker-workflow';
import type { CIConfig } from './types';

describe('generateRemoveDetachedWorkerWorkflow', () => {
  const createConfig = (environments: string[]): CIConfig => ({
    provider: 'github',
    environments,
  });

  it('should return a string', () => {
    const result = generateRemoveDetachedWorkerWorkflow(createConfig(['dev']));
    expect(typeof result).toBe('string');
  });

  it('should be named Remove Detached Worker', () => {
    const result = generateRemoveDetachedWorkerWorkflow(createConfig(['dev']));
    expect(result).toContain('name: Remove Detached Worker');
  });

  it('should use workflow_dispatch trigger', () => {
    const result = generateRemoveDetachedWorkerWorkflow(createConfig(['dev']));
    expect(result).toContain('workflow_dispatch:');
  });

  it('should include environment choice', () => {
    const result = generateRemoveDetachedWorkerWorkflow(
      createConfig(['dev', 'prod']),
    );
    expect(result).toContain('type: choice');
    expect(result).toContain('- dev');
    expect(result).toContain('- prod');
  });

  it('should include worker_name text input', () => {
    const result = generateRemoveDetachedWorkerWorkflow(createConfig(['dev']));
    expect(result).toContain('worker_name:');
    expect(result).toContain("description: 'Worker name to remove");
    expect(result).toContain('type: string');
  });

  it('should include confirm input for double-check', () => {
    const result = generateRemoveDetachedWorkerWorkflow(createConfig(['dev']));
    expect(result).toContain('confirm:');
    expect(result).toContain("description: 'Type worker name again to confirm");
  });

  it('should validate confirmation matches worker name', () => {
    const result = generateRemoveDetachedWorkerWorkflow(createConfig(['dev']));
    expect(result).toContain('Validate confirmation');
    expect(result).toContain('inputs.worker_name');
    expect(result).toContain('inputs.confirm');
  });

  it('should run infra:remove-detached-worker command', () => {
    const result = generateRemoveDetachedWorkerWorkflow(createConfig(['dev']));
    expect(result).toContain('infra:remove-detached-worker');
    expect(result).toContain('--worker');
    expect(result).toContain('--confirm');
  });

  it('should require WIF permissions', () => {
    const result = generateRemoveDetachedWorkerWorkflow(createConfig(['dev']));
    expect(result).toContain('id-token: write');
  });

  it('should include generator comment', () => {
    const result = generateRemoveDetachedWorkerWorkflow(createConfig(['dev']));
    expect(result).toContain('Generated by tsdevstack infra:generate-ci');
  });

  it('should include next steps in summary', () => {
    const result = generateRemoveDetachedWorkerWorkflow(createConfig(['dev']));
    expect(result).toContain('unregister-detached-worker');
    expect(result).toContain('GITHUB_STEP_SUMMARY');
  });
});
