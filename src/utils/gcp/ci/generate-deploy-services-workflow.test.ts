import { describe, it, expect } from '@rstest/core';
import { generateDeployServicesWorkflow } from './generate-deploy-services-workflow';
import type { CIConfig } from './types';

describe('generateDeployServicesWorkflow', () => {
  const createConfig = (environments: string[]): CIConfig => ({
    provider: 'github',
    environments,
  });

  const createServices = () => [
    { name: 'auth-service', type: 'nestjs' },
    { name: 'offers-service', type: 'nestjs' },
    { name: 'frontend', type: 'nextjs' },
  ];

  it('should return a string', () => {
    const result = generateDeployServicesWorkflow(
      createConfig(['dev']),
      createServices(),
    );
    expect(typeof result).toBe('string');
  });

  it('should be named Deploy Services', () => {
    const result = generateDeployServicesWorkflow(
      createConfig(['dev']),
      createServices(),
    );
    expect(result).toContain('name: "Deploy Services');
  });

  it('should use workflow_dispatch trigger', () => {
    const result = generateDeployServicesWorkflow(
      createConfig(['dev']),
      createServices(),
    );
    expect(result).toContain('workflow_dispatch:');
  });

  it('should include environment choice', () => {
    const result = generateDeployServicesWorkflow(
      createConfig(['dev', 'prod']),
      createServices(),
    );
    expect(result).toContain('type: choice');
    expect(result).toContain('- dev');
    expect(result).toContain('- prod');
  });

  it('should generate boolean inputs for each service', () => {
    const result = generateDeployServicesWorkflow(
      createConfig(['dev']),
      createServices(),
    );
    expect(result).toContain('auth_service:');
    expect(result).toContain('offers_service:');
    expect(result).toContain('frontend:');
    expect(result).toContain('type: boolean');
    expect(result).toContain('default: true');
  });

  it('should convert service names with hyphens to underscores', () => {
    const result = generateDeployServicesWorkflow(createConfig(['dev']), [
      { name: 'api-gateway-service', type: 'nestjs' },
    ]);
    expect(result).toContain('api_gateway_service:');
  });

  it('should filter to deployable service types', () => {
    const services = [
      { name: 'auth-service', type: 'nestjs' },
      { name: 'shared-lib', type: 'library' },
    ];
    const result = generateDeployServicesWorkflow(
      createConfig(['dev']),
      services,
    );
    expect(result).toContain('auth_service:');
    expect(result).not.toContain('shared_lib:');
  });

  it('should include spa services', () => {
    const services = [{ name: 'react-app', type: 'spa' }];
    const result = generateDeployServicesWorkflow(
      createConfig(['dev']),
      services,
    );
    expect(result).toContain('react_app:');
  });

  it('should generate service conditions for deployment', () => {
    const result = generateDeployServicesWorkflow(
      createConfig(['dev']),
      createServices(),
    );
    expect(result).toContain('inputs.auth_service');
    expect(result).toContain('inputs.frontend');
    expect(result).toContain('SERVICES=');
  });

  it('should run infra:deploy-services command', () => {
    const result = generateDeployServicesWorkflow(
      createConfig(['dev']),
      createServices(),
    );
    expect(result).toContain('infra:deploy-services');
    expect(result).toContain('--service');
  });

  it('should require WIF permissions', () => {
    const result = generateDeployServicesWorkflow(
      createConfig(['dev']),
      createServices(),
    );
    expect(result).toContain('id-token: write');
  });

  it('should include generator comment', () => {
    const result = generateDeployServicesWorkflow(
      createConfig(['dev']),
      createServices(),
    );
    expect(result).toContain('Generated by tsdevstack infra:generate-ci');
  });

  it('should include Terraform setup and init for reading outputs', () => {
    const result = generateDeployServicesWorkflow(
      createConfig(['dev']),
      createServices(),
    );
    expect(result).toContain('hashicorp/setup-terraform@v3');
    expect(result).toContain('terraform_version: 1.9.0');
    expect(result).toContain('terraform init');
    expect(result).toContain('artifact registry URL');
  });

  it('should generate Terraform files before init', () => {
    const result = generateDeployServicesWorkflow(
      createConfig(['dev']),
      createServices(),
    );
    expect(result).toContain('infra:generate');
  });

  describe('user mode (default)', () => {
    it('should use npx tsdevstack', () => {
      const result = generateDeployServicesWorkflow(
        createConfig(['dev']),
        createServices(),
      );
      expect(result).toContain('npx tsdevstack');
      expect(result).not.toContain('node packages/cli-core/dist/cli.js');
      expect(result).not.toContain('npm link');
    });

    it('should include npm run build', () => {
      const result = generateDeployServicesWorkflow(
        createConfig(['dev']),
        createServices(),
      );
      expect(result).toContain('npm run build');
    });
  });
});
