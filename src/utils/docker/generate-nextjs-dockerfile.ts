/**
 * Generate Dockerfile for Next.js applications
 */

import { DOCKER_NODE_BASE_IMAGE } from '../../constants';

export interface NextJsDockerfileOptions {
  serviceName: string;
  workspacePackages: string[];
  /**
   * When true, wire private-registry auth through the build: include
   * `.npmrc` in the deps-stage COPY and emit a BuildKit env-source
   * secret mount on `npm ci` populated from the build host's
   * `NPM_TOKEN` env var. Same semantics as the NestJS generator —
   * see `NestJsDockerfileOptions.npmAuthEnvSecret`. The .npmrc lives
   * only in the `deps`/`build` intermediate stages — the `production`
   * stage starts from a fresh base, so the final image is clean.
   */
  npmAuthEnvSecret?: boolean;
}

/**
 * Generate a Dockerfile for a Next.js application
 *
 * Requires next.config.ts to have `output: "standalone"` configured.
 *
 * Uses multi-stage build:
 * 1. deps - Install dependencies (DOCKER_NODE_BASE_IMAGE)
 * 2. build - Build the Next.js app
 * 3. production - Minimal runtime with standalone server
 */
export function generateNextJsDockerfile(
  options: NextJsDockerfileOptions,
): string {
  const { serviceName, workspacePackages } = options;

  const packageCopies = workspacePackages
    .map((pkg) => `COPY ${pkg}/package.json ./${pkg}/`)
    .join('\n');

  const npmrcCopy = options.npmAuthEnvSecret ? ' .npmrc' : '';
  const npmCiLine = options.npmAuthEnvSecret
    ? 'RUN --mount=type=cache,target=/root/.npm --mount=type=secret,id=npm_token,env=NPM_TOKEN npm ci'
    : 'RUN --mount=type=cache,target=/root/.npm npm ci';

  return `# Next.js Dockerfile for ${serviceName}
# Generated by: npx tsdevstack infra:generate-docker
# Requires: output: "standalone" in next.config.ts

FROM ${DOCKER_NODE_BASE_IMAGE} AS deps
WORKDIR /app
COPY package.json package-lock.json${npmrcCopy} ./
COPY apps/${serviceName}/package.json ./apps/${serviceName}/
${packageCopies}
${npmCiLine}

FROM deps AS build
COPY . .
ENV NODE_ENV=production
# Build workspace dependencies first (they're TypeScript packages)
${workspacePackages.map((pkg) => `RUN npm run build --workspace=${pkg}`).join('\n')}
# Build the app
RUN npm run build --workspace=apps/${serviceName}

# Production uses slim image (standalone server doesn't need build tools)
FROM ${DOCKER_NODE_BASE_IMAGE} AS production
WORKDIR /app
RUN apt-get update && apt-get install -y --no-install-recommends dumb-init \\
    && rm -rf /var/lib/apt/lists/*
ENV NODE_ENV=production
ENV PORT=8080
ENV HOSTNAME="0.0.0.0"
USER node

# Copy standalone server
COPY --chown=node:node --from=build /app/apps/${serviceName}/.next/standalone ./
# Copy static assets
COPY --chown=node:node --from=build /app/apps/${serviceName}/.next/static ./apps/${serviceName}/.next/static
# Copy public folder
COPY --chown=node:node --from=build /app/apps/${serviceName}/public ./apps/${serviceName}/public

EXPOSE 8080
# Use shell form to override HOSTNAME (container runtimes set it to the container hostname, which Next.js would bind to)
CMD ["dumb-init", "sh", "-c", "HOSTNAME=0.0.0.0 exec node apps/${serviceName}/server.js"]
`;
}
