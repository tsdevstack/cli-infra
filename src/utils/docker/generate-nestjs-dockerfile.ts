/**
 * Generate Dockerfile for NestJS services
 */

import { DOCKER_NODE_BASE_IMAGE } from '../../constants';

export interface NestJsDockerfileOptions {
  serviceName: string;
  workspacePackages: string[];
  hasDatabase: boolean;
  /**
   * When true, wire private-registry auth through the build:
   *   - Include `.npmrc` in the deps-stage COPY (so `${NPM_TOKEN}`
   *     interpolation has a file to interpolate against).
   *   - Emit a BuildKit env-source secret mount on `npm ci`, populated
   *     from the build host's `NPM_TOKEN` env var.
   *
   * The token is mounted as an env var only during the `npm ci` RUN step
   * — it never persists in image layers. Caller is responsible for
   * passing `--secret id=npm_token,env=NPM_TOKEN` to `docker build`; if
   * absent, BuildKit fails fast with a clear error, surfacing the
   * misconfiguration immediately.
   *
   * The .npmrc lives only in the `deps`/`build` intermediate stages —
   * the `production` stage doesn't COPY it across, so the final shipped
   * image is clean. The .npmrc content is just `${NPM_TOKEN}` template
   * (no real secret), so even cache layers pushed to a registry leak
   * nothing sensitive.
   */
  npmAuthEnvSecret?: boolean;
}

/**
 * Generate a Dockerfile for a NestJS service
 *
 * Uses multi-stage build:
 * 1. base - Install dumb-init for proper signal handling
 * 2. deps - Install dependencies with workspace package.json files
 * 3. build - Build the service
 * 4. production - Minimal runtime image
 */
export function generateNestJsDockerfile(
  options: NestJsDockerfileOptions,
): string {
  const { serviceName, workspacePackages, hasDatabase } = options;

  const packageCopies = workspacePackages
    .map((pkg) => `COPY ${pkg}/package.json ./${pkg}/`)
    .join('\n');

  const npmrcCopy = options.npmAuthEnvSecret ? ' .npmrc' : '';
  const npmCiLine = options.npmAuthEnvSecret
    ? 'RUN --mount=type=cache,target=/root/.npm --mount=type=secret,id=npm_token,env=NPM_TOKEN npm ci'
    : 'RUN --mount=type=cache,target=/root/.npm npm ci';

  // For services with Prisma, we need openssl and the prisma folder before npm ci
  // curl is needed for ECS container health checks
  const baseAptPackages = hasDatabase
    ? 'dumb-init openssl curl'
    : 'dumb-init curl';
  const prismaCopyForDeps = hasDatabase
    ? `COPY apps/${serviceName}/prisma ./apps/${serviceName}/prisma`
    : '';
  // For Prisma v7: need prisma/ folder AND prisma.config.js for migrate deploy
  const prismaCopyForProd = hasDatabase
    ? `COPY --chown=node:node --from=build /app/apps/${serviceName}/prisma ./prisma
COPY --chown=node:node --from=build /app/apps/${serviceName}/prisma.config.js ./prisma.config.js`
    : '';

  // Copy workspace packages to production (node_modules has symlinks to these)
  const workspacePackageCopiesForProd = workspacePackages
    .map(
      (pkg) =>
        `COPY --chown=node:node --from=build /app/${pkg}/dist ./${pkg}/dist
COPY --chown=node:node --from=build /app/${pkg}/package.json ./${pkg}/package.json`,
    )
    .join('\n');

  return `# NestJS Dockerfile for ${serviceName}
# Generated by: npx tsdevstack infra:generate-docker

FROM ${DOCKER_NODE_BASE_IMAGE} AS base
WORKDIR /app
RUN apt-get update && apt-get install -y --no-install-recommends ${baseAptPackages} \\
    && rm -rf /var/lib/apt/lists/*

FROM base AS deps
COPY package.json package-lock.json${npmrcCopy} ./
COPY apps/${serviceName}/package.json ./apps/${serviceName}/
${prismaCopyForDeps}
${packageCopies}
${npmCiLine}

FROM deps AS build
COPY . .
ENV NODE_ENV=production
# Build workspace dependencies first (they're TypeScript packages)
${workspacePackages.map((pkg) => `RUN npm run build --workspace=${pkg}`).join('\n')}
# Build the app
RUN npm run build --workspace=apps/${serviceName}

FROM base AS production
ENV NODE_ENV=production
USER node
COPY --chown=node:node --from=build /app/node_modules ./node_modules
COPY --chown=node:node --from=build /app/.tsdevstack/config.json ./.tsdevstack/config.json
${workspacePackageCopiesForProd}
COPY --chown=node:node --from=build /app/apps/${serviceName}/dist ./dist
COPY --chown=node:node --from=build /app/apps/${serviceName}/package.json ./package.json
${prismaCopyForProd}
EXPOSE 8080
CMD ["dumb-init", "node", "dist/main.js"]
`;
}
