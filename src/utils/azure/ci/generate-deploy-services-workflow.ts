/**
 * Generate Deploy Services Workflow
 *
 * Creates the GitHub Actions workflow for deploying services with
 * boolean checkboxes for each service.
 */

/* eslint-disable no-useless-escape */

import type { CIConfig } from './types';
import { toTerraformId } from '../../terraform';

/**
 * Service configuration (subset of FrameworkService)
 */
interface ServiceConfig {
  name: string;
  type: string;
}

/**
 * Generate the deploy-services workflow YAML content
 *
 * @param config - CI configuration with environments
 * @param services - List of deployable services from framework config
 * @param mode - 'user' for end-user projects (npx tsdevstack), 'framework' for monorepo development
 */
export function generateDeployServicesWorkflow(
  config: CIConfig,
  services: ServiceConfig[],
  mode: 'user' | 'framework' = 'user',
): string {
  // Filter to deployable services (nestjs, nextjs, spa)
  const deployableServices = services.filter(
    (s) => s.type === 'nestjs' || s.type === 'nextjs' || s.type === 'spa',
  );

  // Keep lowercase env names (matches terraform dirs, credentials file)
  const envOptions = config.environments
    .map((env) => `          - ${env}`)
    .join('\n');

  // Generate service boolean inputs
  const serviceInputs = deployableServices
    .map(
      (s) => `      ${toTerraformId(s.name)}:
        description: 'Deploy ${s.name}'
        type: boolean
        default: true`,
    )
    .join('\n');

  // Generate if conditions for service list builder
  const serviceConditions = deployableServices
    .map(
      (s) =>
        `          if [ "\${{ inputs.${toTerraformId(s.name)} }}" == "true" ]; then SERVICES="$SERVICES ${s.name}"; fi`,
    )
    .join('\n');

  const cli =
    mode === 'framework'
      ? 'node packages/cli-core/dist/cli.js'
      : 'npx tsdevstack';

  const headerComment =
    mode === 'framework'
      ? `# Framework development workflow - Deploy Services
# Internal: uses monorepo build + npm link`
      : `# Deploy Services workflow - manual trigger
# Generated by tsdevstack infra:generate-ci
# Do not edit manually - regenerate with infra:generate-ci`;

  const workflowName =
    mode === 'framework' ? 'Framework: Deploy Services' : 'Deploy Services';

  const buildSteps =
    mode === 'framework'
      ? `
      - name: Build
        run: npm run build

      # TEMP: Link CLI globally for internal subprocess calls
      - name: Link CLI globally
        run: cd packages/cli-core && npm link
`
      : `
      - name: Build
        run: npm run build
`;

  return `${headerComment}

name: "${workflowName}"

on:
  workflow_dispatch:
    inputs:
      environment:
        description: 'Target environment'
        required: true
        type: choice
        options:
${envOptions}
      tag:
        description: 'Image tag (defaults to commit SHA)'
        required: false
        type: string

      # --- Generated by infra:generate-ci ---
${serviceInputs}
      # --- End generated ---

jobs:
  deploy:
    runs-on: ubuntu-latest
    permissions:
      contents: read
      id-token: write

    steps:
      - uses: actions/checkout@v4

      # Set secret names for dynamic lookup (GitHub requires $GITHUB_ENV for secrets[env.X] pattern)
      - name: Set environment variables
        run: |
          ENV_UPPER=\$(echo '\${{ inputs.environment }}' | tr '[:lower:]' '[:upper:]')
          echo "AZURE_CLIENT_ID_NAME=AZURE_CLIENT_ID_\${ENV_UPPER}" >> \$GITHUB_ENV
          echo "AZURE_TENANT_ID_NAME=AZURE_TENANT_ID_\${ENV_UPPER}" >> \$GITHUB_ENV
          echo "AZURE_SUBSCRIPTION_ID_NAME=AZURE_SUBSCRIPTION_ID_\${ENV_UPPER}" >> \$GITHUB_ENV
          echo "AZURE_LOCATION_NAME=AZURE_LOCATION_\${ENV_UPPER}" >> \$GITHUB_ENV
          echo "IMAGE_TAG=\${{ inputs.tag || github.sha }}" >> \$GITHUB_ENV

      - uses: actions/setup-node@v4
        with:
          node-version: '20'
          cache: 'npm'

      - name: Install dependencies
        run: npm ci
${buildSteps}
      # Authenticate to Azure via OIDC
      - uses: azure/login@v2
        with:
          client-id: \${{ secrets[env.AZURE_CLIENT_ID_NAME] }}
          tenant-id: \${{ secrets[env.AZURE_TENANT_ID_NAME] }}
          subscription-id: \${{ secrets[env.AZURE_SUBSCRIPTION_ID_NAME] }}

      # Set env vars for CLI (getAzureCredentialsFromEnv) and Terraform (ARM_*)
      - name: Set Azure environment variables
        run: |
          echo "AZURE_CLIENT_ID=\${{ secrets[env.AZURE_CLIENT_ID_NAME] }}" >> \$GITHUB_ENV
          echo "AZURE_TENANT_ID=\${{ secrets[env.AZURE_TENANT_ID_NAME] }}" >> \$GITHUB_ENV
          echo "AZURE_SUBSCRIPTION_ID=\${{ secrets[env.AZURE_SUBSCRIPTION_ID_NAME] }}" >> \$GITHUB_ENV
          echo "AZURE_LOCATION=\${{ secrets[env.AZURE_LOCATION_NAME] }}" >> \$GITHUB_ENV
          echo "ARM_CLIENT_ID=\${{ secrets[env.AZURE_CLIENT_ID_NAME] }}" >> \$GITHUB_ENV
          echo "ARM_TENANT_ID=\${{ secrets[env.AZURE_TENANT_ID_NAME] }}" >> \$GITHUB_ENV
          echo "ARM_SUBSCRIPTION_ID=\${{ secrets[env.AZURE_SUBSCRIPTION_ID_NAME] }}" >> \$GITHUB_ENV
          echo "ARM_USE_OIDC=true" >> \$GITHUB_ENV

      - name: Setup Terraform
        uses: hashicorp/setup-terraform@v3
        with:
          terraform_version: 1.9.0

      # Initialize Terraform to read outputs (ACR registry URL)
      - name: Initialize Terraform
        run: |
          cd infrastructure/terraform/\${{ inputs.environment }}
          terraform init

      # Enable containerd for BuildKit cache export support
      - name: Enable containerd image store
        run: |
          echo '{"features":{"containerd-snapshotter":true}}' | sudo tee /etc/docker/daemon.json
          sudo systemctl restart docker

      # Free up disk space for Docker builds
      - name: Free disk space
        run: |
          echo "Disk space before cleanup:"
          df -h /
          sudo rm -rf /usr/share/dotnet /usr/local/lib/android /opt/ghc /opt/hostedtoolcache/CodeQL
          sudo rm -rf /usr/share/swift /usr/local/share/boost /usr/share/miniconda
          docker system prune -af
          echo "Disk space after cleanup:"
          df -h /

      - name: Deploy selected services
        run: |
          # --- Generated by infra:generate-ci ---
          SERVICES=""
${serviceConditions}
          # --- End generated ---

          if [ -z "$SERVICES" ]; then
            echo "No services selected"
            exit 0
          fi

          SERVICES_CSV=$(echo $SERVICES | tr ' ' ',')
          echo "Deploying: $SERVICES_CSV"

          ${cli} infra:deploy-services --env \${{ inputs.environment }} --service "$SERVICES_CSV" --tag \${{ env.IMAGE_TAG }}
`;
}
