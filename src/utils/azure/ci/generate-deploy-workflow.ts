/**
 * Generate Deploy Workflow
 *
 * Creates the GitHub Actions workflow for manual deployments.
 * Uses OIDC for Azure authentication, runs full deployment pipeline.
 */

/* eslint-disable no-useless-escape */

import { renderJobEnvBlock } from '../../npm-auth';
import type { CIConfig } from './types';

/**
 * Generate the deploy workflow YAML content
 */
export function generateDeployWorkflow(
  config: CIConfig,
  options: { npmAuth?: boolean } = {},
): string {
  // Keep lowercase env names (matches terraform dirs, credentials file)
  const envOptions = config.environments
    .map((env) => `          - ${env}`)
    .join('\n');
  const envBlock = renderJobEnvBlock(options.npmAuth ?? false);

  return `# Deploy workflow - manual trigger only
# Generated by tsdevstack infra:init-ci
# Do not edit manually - regenerate with infra:generate-ci

name: "Deploy"

on:
  workflow_dispatch:
    inputs:
      environment:
        description: 'Environment to deploy'
        required: true
        type: choice
        options:
${envOptions}
      tag:
        description: 'Image tag (defaults to commit SHA)'
        required: false
        type: string

jobs:
  deploy:
    runs-on: ubuntu-latest
    permissions:
      contents: read
      id-token: write # Required for OIDC

${envBlock}    steps:
      - uses: actions/checkout@v4

      # Set secret names for dynamic lookup (GitHub requires $GITHUB_ENV for secrets[env.X] pattern)
      - name: Set environment variables
        run: |
          ENV_UPPER=\$(echo '\${{ inputs.environment }}' | tr '[:lower:]' '[:upper:]')
          echo "AZURE_CLIENT_ID_NAME=AZURE_CLIENT_ID_\${ENV_UPPER}" >> \$GITHUB_ENV
          echo "AZURE_TENANT_ID_NAME=AZURE_TENANT_ID_\${ENV_UPPER}" >> \$GITHUB_ENV
          echo "AZURE_SUBSCRIPTION_ID_NAME=AZURE_SUBSCRIPTION_ID_\${ENV_UPPER}" >> \$GITHUB_ENV
          echo "AZURE_LOCATION_NAME=AZURE_LOCATION_\${ENV_UPPER}" >> \$GITHUB_ENV
          echo "IMAGE_TAG=\${{ inputs.tag || github.sha }}" >> \$GITHUB_ENV

      - uses: actions/setup-node@v4
        with:
          node-version: '22'
          cache: 'npm'

      - name: Install dependencies
        run: npm ci

      - name: Security audit
        run: npm audit --audit-level=high
        continue-on-error: true

      - name: Build
        run: npm run build

      - name: Link CLI
        run: npm rebuild @tsdevstack/cli 2>/dev/null || true

      # Authenticate to Azure via OIDC
      - uses: azure/login@v2
        with:
          client-id: \${{ secrets[env.AZURE_CLIENT_ID_NAME] }}
          tenant-id: \${{ secrets[env.AZURE_TENANT_ID_NAME] }}
          subscription-id: \${{ secrets[env.AZURE_SUBSCRIPTION_ID_NAME] }}

      # Set env vars for CLI (getAzureCredentialsFromEnv) and Terraform (ARM_*)
      - name: Set Azure environment variables
        run: |
          echo "AZURE_CLIENT_ID=\${{ secrets[env.AZURE_CLIENT_ID_NAME] }}" >> \$GITHUB_ENV
          echo "AZURE_TENANT_ID=\${{ secrets[env.AZURE_TENANT_ID_NAME] }}" >> \$GITHUB_ENV
          echo "AZURE_SUBSCRIPTION_ID=\${{ secrets[env.AZURE_SUBSCRIPTION_ID_NAME] }}" >> \$GITHUB_ENV
          echo "AZURE_LOCATION=\${{ secrets[env.AZURE_LOCATION_NAME] }}" >> \$GITHUB_ENV
          echo "ARM_CLIENT_ID=\${{ secrets[env.AZURE_CLIENT_ID_NAME] }}" >> \$GITHUB_ENV
          echo "ARM_TENANT_ID=\${{ secrets[env.AZURE_TENANT_ID_NAME] }}" >> \$GITHUB_ENV
          echo "ARM_SUBSCRIPTION_ID=\${{ secrets[env.AZURE_SUBSCRIPTION_ID_NAME] }}" >> \$GITHUB_ENV
          echo "ARM_USE_OIDC=true" >> \$GITHUB_ENV

      - name: Setup Terraform
        uses: hashicorp/setup-terraform@v3
        with:
          terraform_version: 1.9.0

      # Enable containerd for BuildKit cache export support
      - name: Enable containerd image store
        run: |
          echo '{"features":{"containerd-snapshotter":true}}' | sudo tee /etc/docker/daemon.json
          sudo systemctl restart docker

      # Free up disk space for Docker builds (GitHub runner has ~14GB free, we need more)
      - name: Free disk space
        run: |
          echo "Disk space before cleanup:"
          df -h /
          # Remove large unused tools
          sudo rm -rf /usr/share/dotnet /usr/local/lib/android /opt/ghc /opt/hostedtoolcache/CodeQL
          sudo rm -rf /usr/share/swift /usr/local/share/boost /usr/share/miniconda
          # Clean Docker
          docker system prune -af
          echo "Disk space after cleanup:"
          df -h /

      # Step 1: Bootstrap (create resources, add IAM roles)
      - name: Bootstrap
        run: npx tsdevstack infra:bootstrap --env \${{ inputs.environment }}

      # Step 2: Push framework secrets (skip user secrets - no prompts in CI)
      - name: Push Framework Secrets
        run: npx tsdevstack cloud-secrets:push --env \${{ inputs.environment }} --skip-user-secrets

      # Step 3: Full deployment (terraform → services → kong)
      - name: Deploy
        run: npx tsdevstack infra:deploy --env \${{ inputs.environment }} --auto-approve --tag \${{ env.IMAGE_TAG }}

      # Note: Scheduled jobs are deployed separately via 'Deploy Scheduled Jobs' workflow
      # Run after services are healthy: Actions → Deploy Scheduled Jobs
`;
}
