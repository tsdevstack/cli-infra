/**
 * Generate Deploy Infrastructure Workflow
 *
 * Creates the GitHub Actions workflow for deploying Terraform infrastructure.
 */

/* eslint-disable no-useless-escape */

import type { CIConfig } from './types';

/**
 * Generate the deploy-infra workflow YAML content
 *
 * @param config - CI configuration with environments
 */
export function generateDeployInfraWorkflow(config: CIConfig): string {
  // Keep lowercase env names (matches terraform dirs, credentials file)
  const envOptions = config.environments
    .map((env) => `          - ${env}`)
    .join('\n');

  return `# Deploy Infrastructure workflow - manual trigger
# Generated by tsdevstack infra:generate-ci
# Do not edit manually - regenerate with infra:generate-ci

name: "Deploy Infrastructure"

on:
  workflow_dispatch:
    inputs:
      environment:
        description: 'Target environment'
        required: true
        type: choice
        options:
${envOptions}

jobs:
  deploy:
    runs-on: ubuntu-latest
    permissions:
      contents: read
      id-token: write

    steps:
      - uses: actions/checkout@v4

      # Set secret names for dynamic lookup (GitHub requires $GITHUB_ENV for secrets[env.X] pattern)
      - name: Set environment variables
        run: |
          ENV_UPPER=\$(echo '\${{ inputs.environment }}' | tr '[:lower:]' '[:upper:]')
          echo "AZURE_CLIENT_ID_NAME=AZURE_CLIENT_ID_\${ENV_UPPER}" >> \$GITHUB_ENV
          echo "AZURE_TENANT_ID_NAME=AZURE_TENANT_ID_\${ENV_UPPER}" >> \$GITHUB_ENV
          echo "AZURE_SUBSCRIPTION_ID_NAME=AZURE_SUBSCRIPTION_ID_\${ENV_UPPER}" >> \$GITHUB_ENV
          echo "AZURE_LOCATION_NAME=AZURE_LOCATION_\${ENV_UPPER}" >> \$GITHUB_ENV

      - uses: actions/setup-node@v4
        with:
          node-version: '22'
          cache: 'npm'

      - name: Install dependencies
        run: npm ci

      # Authenticate to Azure via OIDC
      - uses: azure/login@v2
        with:
          client-id: \${{ secrets[env.AZURE_CLIENT_ID_NAME] }}
          tenant-id: \${{ secrets[env.AZURE_TENANT_ID_NAME] }}
          subscription-id: \${{ secrets[env.AZURE_SUBSCRIPTION_ID_NAME] }}

      # Set env vars for CLI (getAzureCredentialsFromEnv) and Terraform (ARM_*)
      - name: Set Azure environment variables
        run: |
          echo "AZURE_CLIENT_ID=\${{ secrets[env.AZURE_CLIENT_ID_NAME] }}" >> \$GITHUB_ENV
          echo "AZURE_TENANT_ID=\${{ secrets[env.AZURE_TENANT_ID_NAME] }}" >> \$GITHUB_ENV
          echo "AZURE_SUBSCRIPTION_ID=\${{ secrets[env.AZURE_SUBSCRIPTION_ID_NAME] }}" >> \$GITHUB_ENV
          echo "AZURE_LOCATION=\${{ secrets[env.AZURE_LOCATION_NAME] }}" >> \$GITHUB_ENV
          echo "ARM_CLIENT_ID=\${{ secrets[env.AZURE_CLIENT_ID_NAME] }}" >> \$GITHUB_ENV
          echo "ARM_TENANT_ID=\${{ secrets[env.AZURE_TENANT_ID_NAME] }}" >> \$GITHUB_ENV
          echo "ARM_SUBSCRIPTION_ID=\${{ secrets[env.AZURE_SUBSCRIPTION_ID_NAME] }}" >> \$GITHUB_ENV
          echo "ARM_USE_OIDC=true" >> \$GITHUB_ENV

      - name: Setup Terraform
        uses: hashicorp/setup-terraform@v3
        with:
          terraform_version: 1.9.0

      - name: Bootstrap
        run: npx tsdevstack infra:bootstrap --env \${{ inputs.environment }}

      - name: Push Framework Secrets
        run: npx tsdevstack cloud-secrets:push --env \${{ inputs.environment }} --skip-user-secrets

      - name: Deploy Infrastructure
        run: npx tsdevstack infra:deploy --env \${{ inputs.environment }} --auto-approve --infra-only
`;
}
